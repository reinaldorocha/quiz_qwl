export type LandingContent = {
  [K in keyof typeof landingContent]: K extends "hero"
    ? Omit<(typeof landingContent)["hero"], "headline" | "subheadline"> & {
        headline: string;
        subheadline: string;
      }
    : (typeof landingContent)[K];
};

export type LandingAnchor = "#demo" | "#planos" | "#faq" | "#recursos";

/** Substitui `__PRODUCT__` e aplica headline/subheadline da marca. */
export function resolveLandingContent(
  productName: string,
  landingHeadline: string,
  landingSubheadline: string,
): LandingContent {
  const resolved = JSON.parse(
    JSON.stringify(landingContent).replaceAll("__PRODUCT__", productName),
  ) as LandingContent;

  return {
    ...resolved,
    hero: {
      ...resolved.hero,
      headline: landingHeadline,
      subheadline: landingSubheadline,
    },
  };
}

export function scrollToAnchor(id: LandingAnchor) {
  const element = document.querySelector(id);
  element?.scrollIntoView({ behavior: "smooth", block: "start" });
}
